export function searchHymns(query: string, source: HymnItem[] = mockHymns): HymnItem[] {
  const term = query.trim().toLowerCase();
  if (!term) return source;

  // Check numeric query match
  const isNumberQuery = /^\d+$/.test(term);
  if (isNumberQuery) {
    const num = parseInt(term, 10);
    return source.filter(h => h.number === num || h.number.toString().includes(term));
  }

  // Full text match by title, category, author, chorus, or stanza text
  return source.filter(h => {
    if (h.title.toLowerCase().includes(term)) return true;
    if (h.category.toLowerCase().includes(term)) return true;
    if (h.author && h.author.toLowerCase().includes(term)) return true;
    if (h.chorus && h.chorus.some(line => line.toLowerCase().includes(term))) return true;
    return h.stanzas.some(s => s.lines.some(line => line.toLowerCase().includes(term)));
  });
}
